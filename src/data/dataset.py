from pathlib import Path

import albumentations as A
import numpy as np
import torch
from albumentations.pytorch import ToTensorV2
from torch.utils.data import DataLoader, Dataset

from config import MAX_NUM_OBJS

DATA_DIR = Path(__file__).resolve().parent
TRAIN_DATASET_PATH = DATA_DIR / "train_dataset.pt"
VAL_DATASET_PATH = DATA_DIR / "val_dataset.pt"

OBJECT_TYPE_TO_LABEL = {
    "rectangle": 1,
    "circle": 2,
}
LABEL_TO_OBJECT_TYPE = {label: name for name, label in OBJECT_TYPE_TO_LABEL.items()}


def get_label_object_type(label: dict) -> tuple[int, str]:
    object_type = label.get("shape")

    if object_type is not None:
        if object_type not in OBJECT_TYPE_TO_LABEL:
            raise ValueError(f"Unknown object type: {object_type}")

        return OBJECT_TYPE_TO_LABEL[object_type], object_type

    class_label = label.get("label", OBJECT_TYPE_TO_LABEL["rectangle"])
    return class_label, LABEL_TO_OBJECT_TYPE.get(class_label, "rectangle")


def get_train_transforms() -> A.Compose:
    transforms = [
        A.HorizontalFlip(p=0.5),
        A.VerticalFlip(p=0.5),
        A.OneOf(
            [
                A.ColorJitter(
                    brightness=0.2,
                    contrast=0.2,
                    saturation=0.2,
                    hue=0.05,
                    p=1.0,
                ),
                A.HueSaturationValue(
                    hue_shift_limit=10,
                    sat_shift_limit=20,
                    val_shift_limit=20,
                    p=1.0,
                ),
                A.RandomBrightnessContrast(
                    brightness_limit=0.2,
                    contrast_limit=0.2,
                    p=1.0,
                ),
            ],
            p=0.8,
        ),
        ToTensorV2(),
    ]

    return A.Compose(
        transforms,
        bbox_params=A.BboxParams(
            format="pascal_voc",
            label_fields=["class_labels", "object_types"],
            min_area=1,
            min_visibility=0.0,
        ),
    )


class RectanglesDataset(Dataset):
    """Dataset for the .pt files generated by generate_dataset.ipynb."""

    def __init__(self, dataset_path: str | Path, is_train: bool = False):
        self.dataset_path = Path(dataset_path)
        self.samples = torch.load(self.dataset_path, weights_only=False)
        self.transforms = get_train_transforms() if is_train else None

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        sample = self.samples[idx]
        image = np.array(sample["image"].convert("RGB"))

        bboxes = [label["bbox"] for label in sample["labels"]]
        label_object_types = [
            get_label_object_type(label) for label in sample["labels"]
        ]
        class_labels = [label for label, _ in label_object_types]
        object_types = [object_type for _, object_type in label_object_types]

        if self.transforms is not None:
            transformed = self.transforms(
                image=image,
                bboxes=bboxes,
                class_labels=class_labels,
                object_types=object_types,
            )
            image = transformed["image"].float() / 255.0
            bboxes = transformed["bboxes"]
            class_labels = transformed["class_labels"]
            object_types = transformed["object_types"]
        else:
            image = torch.from_numpy(image.transpose(2, 0, 1)).float() / 255.0

        boxes = torch.as_tensor(bboxes, dtype=torch.float32)
        labels = torch.as_tensor(class_labels, dtype=torch.int64)

        if boxes.numel() == 0:
            boxes = torch.zeros((0, 4), dtype=torch.float32)
        else:
            boxes = boxes.reshape(-1, 4)

        target = {
            "boxes": boxes,
            "labels": labels,
            "object_types": object_types,
        }

        return image, target


def detection_collate_fn(batch):
    images, targets = zip(*batch)

    images = torch.stack(images, dim=0)

    batch_size = len(targets)

    boxes = torch.zeros((batch_size, MAX_NUM_OBJS, 4), dtype=torch.float32)
    labels = torch.zeros((batch_size, MAX_NUM_OBJS), dtype=torch.int64)
    object_mask = torch.zeros((batch_size, MAX_NUM_OBJS), dtype=torch.bool)

    for i, target in enumerate(targets):
        num_objects = min(target["boxes"].shape[0], MAX_NUM_OBJS)

        boxes[i, :num_objects] = target["boxes"][:num_objects]
        labels[i, :num_objects] = target["labels"][:num_objects]
        object_mask[i, :num_objects] = True

    return images, {
        "boxes": boxes,
        "labels": labels,
        "object_mask": object_mask,
    }


def create_dataloader(
    dataset_path: str | Path,
    is_train: bool,
    batch_size: int = 32,
    num_workers: int = 0,
    shuffle: bool | None = None,
) -> DataLoader:
    dataset = RectanglesDataset(dataset_path=dataset_path, is_train=is_train)

    if shuffle is None:
        shuffle = is_train

    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        collate_fn=detection_collate_fn,
    )


def create_train_val_dataloaders(
    train_dataset_path: str | Path = TRAIN_DATASET_PATH,
    val_dataset_path: str | Path = VAL_DATASET_PATH,
    batch_size: int = 32,
    num_workers: int = 0,
) -> tuple[DataLoader, DataLoader]:
    train_loader = create_dataloader(
        dataset_path=train_dataset_path,
        is_train=True,
        batch_size=batch_size,
        num_workers=num_workers,
    )
    val_loader = create_dataloader(
        dataset_path=val_dataset_path,
        is_train=False,
        batch_size=batch_size,
        num_workers=num_workers,
    )

    return train_loader, val_loader


